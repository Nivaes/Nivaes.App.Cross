using System.Collections.Immutable;
using System.Text;
using System.Xml.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace Nivaes.App.Cross.SourceGenerator;

[Generator(LanguageNames.CSharp)]
public class RegisterConvertersGenerator : IIncrementalGenerator
{
    private record struct ConverterInfo(INamedTypeSymbol Type, string? Name);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var converters = context.SyntaxProvider.CreateSyntaxProvider(
                    predicate: static (node, _) => node is ClassDeclarationSyntax,
                    transform: static (ctx, _) => GetConverterType(ctx))
            .Where(static t => t is not null)!;

        var rootNamespace = context.AnalyzerConfigOptionsProvider
                .Select(static (options, _) =>
                {
                    options.GlobalOptions.TryGetValue(
                        "build_property.RootNamespace",
                        out var ns);

                    return ns;
                });

        context.RegisterSourceOutput(
            converters.Collect().Combine(rootNamespace),
            Generate
            );
    }


    private static ConverterInfo? GetConverterType(GeneratorSyntaxContext context)
    {
        var classDeclaration = (ClassDeclarationSyntax)context.Node;

        if (context.SemanticModel.GetDeclaredSymbol(classDeclaration) is not INamedTypeSymbol symbol)
            return null;

        if (symbol.IsAbstract || symbol.IsGenericType)
            return null;

        if (!symbol.AllInterfaces.Any(i => i.ToDisplayString() == "Nivaes.App.Cross.ICrossValueConverter"))
            return null;

        string? name = null;

        var attribute = symbol.GetAttributes()
            .FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == "Nivaes.App.Cross.CrossValueConverterAttribute");

        if (attribute is not null)
        {
            // Busca la propiedad Name
            foreach (var arg in attribute.NamedArguments)
            {
                if (arg.Key == "Name")
                {
                    name = arg.Value.Value as string;
                    break;
                }
            }

            // Opcional: si Name también puede venir por constructor
            if (name is null && attribute.ConstructorArguments.Length > 0)
            {
                name = attribute.ConstructorArguments[0].Value as string;
            }
        }

        return new ConverterInfo(symbol, name);
    }

    private static void Generate(
    SourceProductionContext context,
    (ImmutableArray<ConverterInfo?> converters, string? rootNamespace) input)
    {
        var types = input.converters
            .Where(x => x != null)
            .Cast<ConverterInfo>()
            .GroupBy(x => x.Type, SymbolEqualityComparer.Default)
            .Select(g => g.First())
            .OrderBy(x => x.Type.Name);

        var rootNamespace = string.IsNullOrWhiteSpace(input.rootNamespace) ? string.Empty : $"namespace {input.rootNamespace};";

        var sourceConverters = string.Join(Environment.NewLine,
            types.Select(converter =>
                {
                    if (string.IsNullOrWhiteSpace(converter.Name))
                        return $"ConvertersContainerManagerHelper.New<{converter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>(services),";
                    else
                        return $"ConvertersContainerManagerHelper.New<{converter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)}>(services, \"{converter.Name}\"),";
                }
            ));

        string sourceRegisterConverters = string.Empty;
        if (!string.IsNullOrWhiteSpace(sourceConverters))
        {
            sourceRegisterConverters = $@"
                    ConvertersContainerManagerHelper.RegisterComverters(new[]
                    {{
                       {sourceConverters}
                    }});";
        }

        var source = @$"// This file generated for Nivaes.App.Cross.
            // <auto-generated/>
            using System;
            using Nivaes.App.Cross;
            {rootNamespace}
            internal static class GeneratedConverterExtensions
            {{
                public static IServiceProvider RegisterConverters(this IServiceProvider services)
                {{
                    {sourceRegisterConverters}

                    return services;
                }}
            }}
        ";

        context.AddSource(
            "GeneratedConverterExtensions.g.cs",
            SourceText.From(source, Encoding.UTF8));
    }
}