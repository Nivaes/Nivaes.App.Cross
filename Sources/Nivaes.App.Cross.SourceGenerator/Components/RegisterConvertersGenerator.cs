[Generator(LanguageNames.CSharp)]
public class RegisterConvertersGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var converters = context.SyntaxProvider.CreateSyntaxProvider(
                    predicate: static (node, _) => node is ClassDeclarationSyntax,
                    transform: static (ctx, _) => GetConverterType(ctx))
            .Where(static t => t is not null)!;

        var rootNamespace = context.AnalyzerConfigOptionsProvider
                .Select(static (options, _) =>
                {
                    options.GlobalOptions.TryGetValue(
                        "build_property.RootNamespace",
                        out var ns);

                    //context.Compilation.AssemblyName

                    return ns;
                });

        //var aa = converters.Collect().Combine(rootNamespace);
        //var bb = aa.Select(k =>
        //{
        //    return k;
        //});

        context.RegisterSourceOutput(
            converters.Collect().Combine(rootNamespace),
            Generate
            );
    }

